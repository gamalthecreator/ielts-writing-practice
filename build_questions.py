"""Rebuild task1.js from ../IELTS_Task1_Practice.md. Run again whenever the MD file changes:
    python build_questions.py
"""
import json, os, re
import markdown

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "IELTS_Task1_Practice.md")


LIST = re.compile(r"^(\s*[-*] |\s*\d+\. )")


def html(text):
    # python-markdown needs a blank line before a list that follows a paragraph
    out = []
    for line in text.strip().splitlines():
        if LIST.match(line) and out and out[-1].strip() and not LIST.match(out[-1]):
            out.append("")
        out.append(line)
    return markdown.markdown("\n".join(out), extensions=["tables"])


lines = open(SRC, encoding="utf-8-sig").read().splitlines()
qs, tips, sec, cur = [], {}, None, None
for line in lines:
    if line.startswith("# "):
        sec, cur = line[2:].strip(), None
        tips[sec] = []
        continue
    m = re.match(r"## Q(\d+)\. (.*)", line)
    if m:
        cur = {"n": int(m[1]), "title": m[2].strip(), "section": sec, "lines": []}
        qs.append(cur)
        continue
    if line.startswith("## ") or line.strip() == "---":
        cur = None
        if line.strip() == "---":
            continue
    (cur["lines"] if cur else tips.setdefault(sec, [])).append(line)

out = []
for q in qs:
    text = "\n".join(q.pop("lines"))
    img = re.search(r"!\[[^\]]*\]\(([^)]+)\)", text)
    prompt = re.search(r"^\*\*(.+?)\*\*\s*$", text, re.M)
    instr = re.search(r"^\*([^*].+?)\*\s*$", text, re.M)
    hint = re.search(r"<details><summary>.*?</summary>(.*?)</details>", text, re.S)
    assert img and prompt and instr and hint, f"Q{q['n']} is missing image/prompt/instruction/hint"
    body = text
    for part in (img[0], prompt[0], instr[0], hint[0]):
        body = body.replace(part, "")
    q.update(img="../" + img[1], prompt=prompt[1], instr=instr[1],
             hintHtml=html(hint[1]), dataHtml=html(body))
    out.append(q)

assert [q["n"] for q in out] == list(range(1, len(out) + 1)), "question numbers not sequential"
tip_html = {k: html("\n".join(v)) for k, v in tips.items() if k and "".join(v).strip()}
with open(os.path.join(HERE, "task1.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by build_questions.py from IELTS_Task1_Practice.md. Do not edit by hand.\n")
    f.write("window.TASK1 = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
    f.write("window.TASK1_TIPS = " + json.dumps(tip_html, ensure_ascii=False, indent=1) + ";\n")
print(f"{len(out)} questions, sections: {sorted({q['section'] for q in out})}")
